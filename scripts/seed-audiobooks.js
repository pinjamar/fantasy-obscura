async function seed() {
  console.log(`Updating ${AUDIOBOOK_DATA.length} books with audiobook data...`);
  let updated = 0;
  let failed = 0;

  for (const entry of AUDIOBOOK_DATA) {
    const { slug, ...fields } = entry;
    const { error } = await supabase
      .from('books')
      .update(fields)
      .eq('slug', slug);

    if (error) {
      console.error(`✗ ${slug}: ${error.message}`);
      failed++;
    } else {
      console.log(`✓ ${slug}`);
      updated++;
    }
  }

  console.log(`\nDone: ${updated} updated, ${failed} failed.`);
}

seed().catch(console.error);
